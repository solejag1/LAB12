"""
Задание 10. Регулярные выражения для банковского приложения.

Промпт: «Сгенерируй регулярные выражения для валидации банковских реквизитов:
1) Номер счёта — 20 цифр (формат российского банковского счёта).
2) Номер карты — 16 цифр, может разделяться пробелами или дефисами группами по 4.
3) Номер телефона — российский формат: +7 или 8, затем 10 цифр.
Также сгенерируй Python-скрипт для тестирования каждого выражения
на 5 валидных и 5 невалидных примерах.»
"""

import re

# ── Регулярные выражения ──────────────────────────────────────────────────────

# Номер счёта: ровно 20 цифр
ACCOUNT_NUMBER_RE = re.compile(r"^\d{20}$")

# Номер карты: 16 цифр, разделённые пробелами/дефисами или слитно
# Пример валидного: "4111111111111111" или "4111 1111 1111 1111" или "4111-1111-1111-1111"
CARD_NUMBER_RE = re.compile(r"^(\d{4}[\s-]?){3}\d{4}$")

# Российский телефон: +7XXXXXXXXXX или 8XXXXXXXXXX (10 цифр после кода)
PHONE_RE = re.compile(r"^(\+7|8)\d{10}$")


# ── Тестовый набор ────────────────────────────────────────────────────────────

def run_tests(label: str, pattern: re.Pattern, valid: list[str], invalid: list[str]) -> None:
    print(f"\n{'='*60}")
    print(f"Тест: {label}")
    print(f"Паттерн: {pattern.pattern}")
    print("-" * 60)

    all_passed = True

    print("  Валидные (ожидается MATCH):")
    for value in valid:
        match = bool(pattern.match(value))
        status = "✅ PASS" if match else "❌ FAIL"
        if not match:
            all_passed = False
        print(f"    {status}  «{value}»")

    print("  Невалидные (ожидается NO MATCH):")
    for value in invalid:
        match = bool(pattern.match(value))
        status = "✅ PASS" if not match else "❌ FAIL"
        if match:
            all_passed = False
        print(f"    {status}  «{value}»")

    result = "✅ Все тесты пройдены" if all_passed else "❌ Есть ошибки"
    print(f"\n  Итог: {result}")


if __name__ == "__main__":
    # ── Номер счёта ───────────────────────────────────────────────────────────
    run_tests(
        label="Номер счёта (20 цифр)",
        pattern=ACCOUNT_NUMBER_RE,
        valid=[
            "12345678901234567890",
            "40817810099910004312",
            "30101810400000000225",
            "40802810200001234567",
            "00000000000000000001",
        ],
        invalid=[
            "1234567890123456789",    # 19 цифр
            "123456789012345678901",  # 21 цифра
            "1234567890ABCD567890",   # буквы
            "1234 5678 9012 3456 78", # пробелы
            "",                       # пустая строка
        ],
    )

    # ── Номер карты ───────────────────────────────────────────────────────────
    run_tests(
        label="Номер карты (16 цифр, допустимы разделители)",
        pattern=CARD_NUMBER_RE,
        valid=[
            "4111111111111111",        # слитно
            "4111 1111 1111 1111",     # пробелы
            "4111-1111-1111-1111",     # дефисы
            "5500005555555559",        # Mastercard
            "4000 1234 5678 9010",     # Visa с пробелами
        ],
        invalid=[
            "411111111111111",         # 15 цифр
            "41111111111111111",       # 17 цифр
            "4111 1111 1111 111X",     # буква
            "4111  1111  1111  1111",  # двойные пробелы
            "",                        # пустая строка
        ],
    )

    # ── Телефон ───────────────────────────────────────────────────────────────
    run_tests(
        label="Российский телефон (+7/8 + 10 цифр)",
        pattern=PHONE_RE,
        valid=[
            "+79161234567",
            "+79991234567",
            "89161234567",
            "80001234567",
            "+71234567890",
        ],
        invalid=[
            "79161234567",    # нет + перед 7
            "+7916123456",    # 9 цифр после кода
            "+7 916 123 45 67",  # пробелы
            "+89161234567",   # +8 недопустимо
            "phone",          # не число
        ],
    )
